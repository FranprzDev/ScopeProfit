#!/usr/bin/env node
/**
 * Generates src/registry.ts: one static import per MCP tool file in
 * apps/api/src/modules/mcp/tools/. Keeps the Worker's tool list in lockstep with the API's
 * xmcp tool directory — a tool added there fails the build until the registry regenerates.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const toolsDir = join(here, '../..', 'apps/api/src/modules/mcp/tools');
const files = readdirSync(toolsDir)
  .filter((file) => file.endsWith('.ts'))
  .sort();

const imports = files
  .map((file, index) => {
    const name = file.replace(/\.ts$/, '');
    return `import tool${index}, { metadata as metadata${index}, schema as schema${index} } from '../../api/src/modules/mcp/tools/${name}';`;
  })
  .join('\n');

const entries = files
  .map((file, index) => {
    const name = file.replace(/\.ts$/, '');
    return `  { name: '${name}', metadata: metadata${index}, schema: schema${index}, handler: tool${index} },`;
  })
  .join('\n');

writeFileSync(
  join(here, 'src/registry.ts'),
  `// Generated by gen-registry.mjs — do not edit by hand.
import type { CallToolResult } from '@modelcontextprotocol/sdk/types.js';
${imports}

export interface ToolEntry {
  name: string;
  metadata: { name: string; description: string; annotations?: Record<string, unknown> };
  schema: Record<string, unknown>;
  handler: (args: never) => Promise<CallToolResult>;
}

export const TOOLS: ToolEntry[] = [
${entries}
];
`,
);
console.log(`registry: ${files.length} tools`);
